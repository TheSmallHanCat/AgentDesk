"""Generate the supported JSON Schema subset deterministically without network access."""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = json.loads((ROOT / "protocol/hello.schema.json").read_text(encoding="utf-8"))


def snake(value: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", value).lower()


def field_type(node: dict, lang: str) -> str:
    if "$ref" in node:
        if not node["$ref"].startswith("#/$defs/"):
            raise ValueError("Only local definition references are supported")
        return node["$ref"].split("/")[-1]
    if lang != "rust" and ("const" in node or "enum" in node):
        values = [node["const"]] if "const" in node else node["enum"]
        literals = [json.dumps(v) for v in values]
        return " | ".join(literals) if lang == "ts" else f"Literal[{', '.join(literals)}]"
    kind = node.get("type")
    if kind in ("string", "integer", "number", "boolean"):
        return {"ts": {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}, "rust": {"string": "String", "integer": "u64" if node.get("minimum", -1) >= 0 else "i64", "number": "f64", "boolean": "bool"}, "python": {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}}[lang][kind]
    if kind == "array":
        item = field_type(node["items"], lang)
        return {"ts": f"Array<{item}>", "rust": f"Vec<{item}>", "python": f"list[{item}]"}[lang]
    if kind == "object" and isinstance(node.get("additionalProperties"), dict):
        value = field_type(node["additionalProperties"], lang)
        return {"ts": f"Record<string, {value}>", "rust": f"std::collections::BTreeMap<String, {value}>", "python": f"dict[str, {value}]"}[lang]
    raise ValueError(f"Unsupported field schema: {node}")


def generate() -> dict[Path, str]:
    ts = ["// Generated by protocol/generate.py. Do not edit."]
    rust = ["// Generated by protocol/generate.py. Do not edit.", "use serde::{Deserialize, Serialize};"]
    py = ['"""Generated by protocol/generate.py. Do not edit."""', "from __future__ import annotations", "from dataclasses import dataclass", "from typing import Literal"]
    for name, definition in SCHEMA["$defs"].items():
        if definition.get("type") != "object" or definition.get("additionalProperties") is not False:
            raise ValueError("Definitions must be closed objects")
        props = definition["properties"]
        required = definition.get("required", [])
        ts.extend(["", f"export interface {name} {{"])
        rust.extend(["", "#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]", '#[serde(rename_all = "camelCase", deny_unknown_fields)]', f"pub struct {name} {{"])
        py.extend(["", "", "@dataclass(kw_only=True)", f"class {name}:"])
        for key, node in props.items():
            optional = key not in required
            ts.append(f"  {key}{'?' if optional else ''}: {field_type(node, 'ts')};")
            rt = field_type(node, "rust")
            if optional:
                rust.append('    #[serde(default, skip_serializing_if = "Option::is_none")]')
                rt = f"Option<{rt}>"
            rust.append(f"    pub {snake(key)}: {rt},")
            pt = field_type(node, "python")
            py.append(f"    {key}: {pt}{' | None = None' if optional else ''}")
        ts.append("}")
        rust.append("}")
    return {ROOT / "src/protocol/generated.ts": "\n".join(ts) + "\n", ROOT / "src-tauri/src/host/protocol.rs": "\n".join(rust) + "\n", ROOT / "host/agentdesk_host/protocol.py": "\n".join(py) + "\n"}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Generated protocol files are stale: " + ", ".join(stale))
    print("Protocol types: 3 outputs checked" if args.check else "Protocol types: 3 outputs generated")


if __name__ == "__main__":
    main()
